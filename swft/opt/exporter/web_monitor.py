import hashlib  # Импортируем библиотеку для работы с хэшами
import requests  # Импортируем библиотеку для отправки HTTP-запросов
import time  # Импортируем библиотеку для работы с задержками


# Функция для получения хэша содержимого веб-страницы
def get_page_hash(url):
    """
    Загружает содержимое страницы по указанному URL и вычисляет её MD5-хэш.

    :param url: URL-адрес веб-страницы.
    :return: MD5-хэш содержимого страницы или None, если произошла ошибка.
    """

    # Большинство сайтов проверяют заголовок User-Agent, чтобы определить, что
    # запрос сделан браузером. Поэтому будем добавлять этот заголовок к запросу.
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/114.0.0.0 Safari/537.36"
    }

    try:
        # Отправляем GET-запрос к указанному URL
        response = requests.get(url, headers=headers)
        # Проверяем успешность запроса (код 200)
        response.raise_for_status()
        # Получаем содержимое страницы как текст
        page_content = response.text
        # Вычисляем MD5-хэш от содержимого страницы
        return hashlib.md5(page_content.encode('utf-8')).hexdigest()
    except requests.RequestException as e:
        # Если произошла ошибка (например, страница недоступна), выводим сообщение об ошибке
        print(f"Ошибка при загрузке страницы: {e}")
        return None  # Возвращаем None, чтобы сигнализировать об ошибке


# Функция для мониторинга изменений на веб-странице
def monitor_page(url, interval):
    """
    Проверяет изменения на веб-странице с заданным интервалом времени.

    :param url: URL-адрес веб-страницы.
    :param interval: Интервал проверки в секундах.
    """
    print(f"Начинаем мониторинг страницы: {url}")

    # Получаем хэш содержимого страницы на момент запуска скрипта
    previous_hash = get_page_hash(url)

    # Если хэш не удалось получить, выводим сообщение и завершаем выполнение
    if previous_hash is None:
        print("Не удалось получить содержимое страницы. Проверьте URL.")
        return

    # Начинаем бесконечный цикл для периодической проверки страницы
    while True:
        # Ждём заданный интервал времени перед следующей проверкой
        time.sleep(interval)

        # Получаем хэш текущего содержимого страницы
        current_hash = get_page_hash(url)

        # Если хэш текущего содержимого не удалось получить, продолжаем цикл
        if current_hash is None:
            print("Ошибка при загрузке страницы. Продолжаем мониторинг...")
            continue

        # Сравниваем текущий хэш с предыдущим
        if current_hash != previous_hash:
            # Если хэши отличаются, выводим сообщение об обновлении страницы
            print(f"⚡ Страница обновлена! {url}")
            # Обновляем сохранённый хэш
            previous_hash = current_hash
        else:
            # Если хэши совпадают, выводим сообщение об отсутствии изменений
            print(f"👌 Изменений нет. ({time.strftime('%H:%M:%S')})")


# Указываем URL веб-страницы для мониторинга
url_to_monitor = "https://time.is/"

# Указываем интервал проверки в секундах
check_interval = 60  # Проверяем страницу каждые 60 секунд

# Запускаем функцию мониторинга
monitor_page(url_to_monitor, check_interval)
